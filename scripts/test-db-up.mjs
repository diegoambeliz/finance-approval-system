// Ensures an isolated integration-test database exists, derived from the
// dev DATABASE_URL in .env (same server, distinct database name so it can
// never be confused with the dev database at the connection-string level).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import pg from "pg";

const DEV_ENV_PATH = ".env";
const TEST_ENV_PATH = ".env.test";

function readDevDatabaseUrl() {
  if (!existsSync(DEV_ENV_PATH)) {
    throw new Error(`${DEV_ENV_PATH} not found - can't derive a test database from it.`);
  }
  const raw = readFileSync(DEV_ENV_PATH, "utf8");
  const match = raw.match(/^DATABASE_URL=(.*)$/m);
  if (!match) throw new Error(`DATABASE_URL not found in ${DEV_ENV_PATH}`);
  return match[1].trim().replace(/^"(.*)"$/, "$1");
}

function deriveTestUrl(devUrl) {
  const parsed = new URL(devUrl);
  const devDbName = parsed.pathname.replace(/^\//, "");
  if (!devDbName) throw new Error("Dev DATABASE_URL has no database name in its path.");

  const testDbName = `${devDbName}_test`;
  parsed.pathname = `/${testDbName}`;
  return { testUrl: parsed.toString(), testDbName, devDbName };
}

function writeTestEnv(testUrl) {
  const content = `# Generated by scripts/test-db-up.mjs from .env - do not point this at the dev database.\nDATABASE_URL="${testUrl}"\n`;
  writeFileSync(TEST_ENV_PATH, content);
}

async function ensureDatabaseExists(testUrl, testDbName) {
  if (!testDbName.endsWith("_test")) {
    // Guard against ever running this against something that isn't clearly a test DB.
    throw new Error(`Refusing to operate on "${testDbName}" - name must end with "_test".`);
  }

  const adminUrl = new URL(testUrl);
  adminUrl.pathname = "/postgres"; // maintenance DB, always present, used only to run CREATE DATABASE

  const client = new pg.Client({ connectionString: adminUrl.toString() });
  await client.connect();

  try {
    const { rows } = await client.query("SELECT 1 FROM pg_database WHERE datname = $1", [testDbName]);
    if (rows.length === 0) {
      await client.query(`CREATE DATABASE "${testDbName}"`);
      console.log(`Created test database "${testDbName}".`);
    } else {
      console.log(`Test database "${testDbName}" already exists.`);
    }
  } finally {
    await client.end();
  }
}

const devUrl = readDevDatabaseUrl();
const { testUrl, testDbName, devDbName } = deriveTestUrl(devUrl);

writeTestEnv(testUrl);
console.log(`Wrote ${TEST_ENV_PATH} -> database "${testDbName}" (derived from dev database "${devDbName}").`);

await ensureDatabaseExists(testUrl, testDbName);
